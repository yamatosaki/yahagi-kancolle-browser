      'ZIP 中存在相同目标资源：',
      'ZIP 文件长度或校验和错误：',
      '无法更新同名资源：',
      'Invalid or unsupported display table: ',
    ]) {
      if (detail.startsWith(prefix)) {
        return _scanMessage(prefix)! + detail.substring(prefix.length);
      }
    }
    return detail;
