// These expected bands were generated by executing Poi's actual
// sumSubgoals/getIntentByPercent and TaskRow selection, rather than a second
// implementation of our thresholds. Each character is count 0..required.
// Poi revision: 725029997b84729df6394e1f107079b8e9437f36.
// task-panel.tsx SHA-256:
// 85384cafc053e7f4f54a00251f69f1434d15a57a39c4f78c1e9827c0aa9342ba.
// n=none, w=warning, p=primary, s=success. These are semantic intent bands;
// our theme colors intentionally follow our palette rather than Blueprint RGB.
const _verifiedPoiBands = <int, String>{
  1: 'ns',
  2: 'nws',
  3: 'nnws',
  5: 'nnnwps',
  10: 'nnnnnwwwpps',
  78:
      'nnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnn'
      'wwwwwwwwwwwwwwwwwwwwwwww'
      'ppppppppppppppps',
};

const _fallback = [
  (flag: 0, poiLabel: 'In progress', appLabel: '＜50%', band: 'n'),
  (flag: 1, poiLabel: '50%', appLabel: '50%+', band: 'w'),
  (flag: 2, poiLabel: '80%', appLabel: '80%+', band: 'p'),
];

// Source-verified composite outputs. Uneven 62/78 must stay warning even
// though three of the four individual subgoals have already reached 100%.
const _verifiedPoiComposites = [
  _Composite('214-zero', 214, 2, [0, 0, 0, 0], 0, 78, 'none'),
  _Composite('214-overlapping-first-boss', 214, 2, [1, 1, 1, 1], 4, 78, 'none'),
  _Composite('214-rank-only', 214, 1, [6, 0, 0, 0], 6, 78, 'none'),
  _Composite('214-halfway', 214, 0, [3, 6, 12, 18], 39, 78, 'warning'),
  _Composite(
    '214-uneven-before-eighty',
    214,
    2,
    [6, 12, 24, 20],
    62,
    78,
    'warning',
  ),
  _Composite(
    '214-uneven-at-eighty',
    214,
    0,
    [6, 12, 24, 21],
    63,
    78,
    'primary',
  ),
  _Composite('214-full', 214, 0, [6, 12, 24, 36], 78, 78, 'success'),
  _Composite('428-three-subgoals', 428, 2, [2, 0, 1], 3, 6, 'warning'),
];

const _verifiedCompositeRequirements = <int, Map<String, int>>{
  214: {
    'battle_rank_s': 6,
    'battle_boss_win': 12,
    'battle_boss': 24,
    'sally': 36,
  },
  428: {
    'mission_success@対潜警戒任務': 2,
    'mission_success@海峡警備行動': 2,
    'mission_success@長時間対潜警戒': 2,
  },
};

void main() {
  final goals = _assetGoals();
  final oraclePath = Platform.environment['YAHAGI_POI_QUEST_DISPLAY_ORACLE'];
  final oracle = oraclePath == null
      ? null
      : (jsonDecode(File(oraclePath).readAsStringSync()) as Map)
            .cast<String, dynamic>();

  test('verified fixtures cover every count, including exact boundaries', () {
    for (final fixture in _verifiedPoiBands.entries) {
      expect(fixture.value.length, fixture.key + 1);
      expect(fixture.value[0], 'n');
      expect(fixture.value[fixture.key], 's');
    }
    expect(_verifiedPoiBands[5]![2], 'n');
    expect(_verifiedPoiBands[5]![3], 'w');
    expect(_verifiedPoiBands[5]![4], 'p');
    expect(_verifiedPoiBands[10]![5], 'w');
    expect(_verifiedPoiBands[10]![8], 'p');
    expect(_verifiedPoiBands[78]![38], 'n');
    expect(_verifiedPoiBands[78]![39], 'w');
    expect(_verifiedPoiBands[78]![62], 'w');
    expect(_verifiedPoiBands[78]![63], 'p');
  });

  for (final mode in AppThemeMode.values) {
    testWidgets('restored composite subgoals match Poi aggregates in $mode', (
      tester,
    ) async {
      final context = await _context(tester, mode);
      for (final fixture in _verifiedPoiComposites) {
        final row = fixture.toOracleRow();
        final quest = await _restoreComposite(row, goals);
        _expectCompositeDisplay(quest, row, context);
      }
    });

    testWidgets('Poi record bands and count priority in $mode', (tester) async {
      final context = await _context(tester, mode);
      final colors = _intentColors(context);
      for (final fixture in _verifiedPoiBands.entries) {
        final total = fixture.key;
        for (var current = 0; current <= total; current++) {
          for (final flag in [0, 1, 2]) {
            final quest = _quest(current: current, total: total, flag: flag);
            final reason = '$mode count=$current/$total flag=$flag';
            expect(
              quest.displayProgressLabel,
              '$current/$total',
              reason: reason,
            );
            expect(
              quest.progressColor(context),
              colors[fixture.value[current]],
              reason: reason,
            );
            expect(
              questProgressColor(
                context,
                current: current,
                total: total,
                progressFlag: flag,
              ),
              colors[fixture.value[current]],
              reason: reason,
            );
          }
        }
      }
    });

    testWidgets(
      'Poi no-record fallback bands with explicit app labels in $mode',
      (tester) async {
        final context = await _context(tester, mode);
        final colors = _intentColors(context);
        for (final row in _fallback) {
          for (final state in [1, 2, 3]) {
            final quest = _quest(flag: row.flag, state: state);
            final complete = state == 3;
            expect(
              quest.displayProgressLabel,
              complete ? '100%' : row.appLabel,
            );
            expect(
              quest.progressColor(context),
              colors[complete ? 's' : row.band],
            );
          }
        }
      },
    );

    testWidgets('server completion deliberately overrides Poi record in $mode', (
      tester,
    ) async {
      final context = await _context(tester, mode);
      final colors = _intentColors(context);
      for (final fixture in _verifiedPoiBands.entries) {
        final total = fixture.key;
        for (var current = 0; current <= total; current++) {
          for (final flag in [0, 1, 2]) {
            final quest = _quest(
              current: current,
              total: total,
              flag: flag,
              state: 3,
              verified: false,
            );
            final reason = 'server complete, cached $current/$total flag=$flag';
            // Poi TaskRow keeps the record label even at state 3. The app's
            // authoritative server result must continue to win over old counts.
            expect(quest.exactProgressLabel, '$current/$total', reason: reason);
            expect(quest.displayProgressLabel, '100%', reason: reason);
            expect(quest.progressColor(context), colors['s'], reason: reason);
            expect(quest.isServerCompleted, isTrue, reason: reason);
          }
        }
      }
    });

    testWidgets('Poi full-count green does not imply claimability in $mode', (
      tester,
    ) async {
      final context = await _context(tester, mode);
      final catalog = QuestCatalog(const [
        QuestCatalogEntry(
          gameId: 912,
          code: 'By3',
          name: 'test',
          description: '',
        ),
      ]);
      for (final total in _verifiedPoiBands.keys) {
        final quest = _quest(current: total, total: total, verified: false);
        expect(quest.progressColor(context), _intentColors(context)['s']);
        expect(quest.displayProgressLabel, '$total/$total');
        expect(quest.isCompleted, isFalse);
        expect(
          catalog.project({quest.id: quest}).byGameId(quest.id).status,
          QuestStatus.inProgress,
        );
      }
    });

    testWidgets('zero-total record retains the app fallback guard in $mode', (
      tester,
    ) async {
      final context = await _context(tester, mode);
      final colors = _intentColors(context);
      for (final row in _fallback) {
        final quest = _quest(current: 0, total: 0, flag: row.flag);
        // Poi evaluates 0 / 0 as NaN and its final branch returns success.
        // The app requires a positive total and retains the server flag band.
        expect(quest.displayProgressLabel, '0/0');
        expect(quest.progressColor(context), colors[row.band]);
        expect(quest.isLocallyCompleted, isFalse);
      }
    });
  }

  if (oracle != null) {
    test(
      'source-derived Poi oracle confirms all checked-in expected fixtures',
      () {
        expect(oracle['schema'], 'poi-quest-display-oracle-v1');
        expect(
          oracle['sourceRevision'],
          '725029997b84729df6394e1f107079b8e9437f36',
        );
        expect(
          oracle['sourceSha256'],
          '85384cafc053e7f4f54a00251f69f1434d15a57a39c4f78c1e9827c0aa9342ba',
        );
        expect(oracle['bands'], {
          for (final row in _verifiedPoiBands.entries) '${row.key}': row.value,
        });
        expect((oracle['records'] as List).length, 630);
        expect((oracle['fallback'] as List).length, 9);
        expect((oracle['emptyRecord'] as List).length, 3);
        expect(oracle['composites'], [
          for (final fixture in _verifiedPoiComposites) fixture.toOracleRow(),
        ]);
      },
    );

    for (final mode in AppThemeMode.values) {
      testWidgets('actual Poi TaskRow oracle differential in $mode', (
        tester,
      ) async {
        final context = await _context(tester, mode);
        final colors = _intentColors(context);
        for (final raw in oracle['composites'] as List) {
          final row = (raw as Map).cast<String, dynamic>();
          final quest = await _restoreComposite(row, goals);
          _expectCompositeDisplay(quest, row, context);
        }
        for (final raw in oracle['records'] as List) {
          final row = (raw as Map).cast<String, dynamic>();
          final quest = _quest(
            current: row['current'] as int,
            total: row['total'] as int,
            flag: row['flag'] as int,
            state: row['state'] as int,
          );
          expect(row['count'], quest.progressCurrent);
          expect(row['required'], quest.progressRequired);
          final poiLabel = (row['label'] as String).replaceAll(' / ', '/');
          if (quest.isServerCompleted) {
            expect(quest.displayProgressLabel, '100%');
            expect(quest.progressColor(context), colors['s']);
          } else {
            expect(quest.displayProgressLabel, poiLabel);
            expect(quest.progressColor(context), colors[row['intent']]);
          }
          // Even with state 3, Poi's actual source always selects the record.
          expect(poiLabel, quest.exactProgressLabel);
          expect(
            row['intent'],
            _intentName(
              _verifiedPoiBands[quest.progressRequired]![quest
                  .progressCurrent!],
            ),
          );
        }
        for (final raw in oracle['fallback'] as List) {
          final row = (raw as Map).cast<String, dynamic>();
          final flag = row['flag'] as int;
          final quest = _quest(flag: flag, state: row['state'] as int);
          expect(quest.progressColor(context), colors[row['intent']]);
          expect(
            row['label'],
            quest.isServerCompleted ? 'Completed' : _fallback[flag].poiLabel,
          );
          expect(
            quest.displayProgressLabel,
            quest.isServerCompleted ? '100%' : _fallback[flag].appLabel,
          );
        }
        for (final raw in oracle['emptyRecord'] as List) {
          final row = (raw as Map).cast<String, dynamic>();
          expect(row['count'], 0);
          expect(row['required'], 0);
          expect(row['label'], '0 / 0');
          expect(row['intent'], 'success');
          final quest = _quest(current: 0, total: 0, flag: row['flag'] as int);
          expect(quest.progressColor(context), isNot(colors[row['intent']]));
        }
      });
    }
  }
}

Map<int, QuestProgressGoal> _assetGoals() {
  final raw =
      jsonDecode(
            File('assets/data/quest-progress-goals.json').readAsStringSync(),
          )
          as Map;
  return {
    for (final id in _verifiedCompositeRequirements.keys)
      id: QuestProgressGoal(id, Map<String, dynamic>.from(raw['$id'] as Map)),
  };
}

Future<GameQuest> _restoreComposite(
  Map<String, dynamic> row,
  Map<int, QuestProgressGoal> goals,
) async {
  final id = row['questId'] as int;
  final goal = goals[id]!;
  final apiType = id == 214 ? 2 : 5;
  final now = DateTime.utc(2026, 10, 29, 3);
  expect(
    {for (final step in goal.steps.entries) step.key: step.value['required']},
    row['requirements'],
    reason: '${row['name']}: asset requirements must match actual Poi data',
  );
  final storage = _CompositeStorage(
    jsonEncode({
      'account': 100,
      'records': {
        '$id': {
          'period': questPeriodKey(goal.type, apiType, now),
          'ruleType': goal.type,
          'ruleRevision': goal.revision,
          'type': apiType,
          'counts': row['counts'],
          'claimed': false,
          'blocked': false,
        },
      },
      // No aggregate current/required is supplied here. The production restore
      // and projection must derive both from the ledger's separate subgoals.
      'active': [
        {
          'id': id,
          'title': 'composite',
          'detail': '',
          'category': 2,
          'type': apiType,
          'state': 2,
          'flag': row['flag'],
          'updated': now.toIso8601String(),
        },
      ],
    }),
  );
  final engine = QuestProgressEngine(goals: goals, storage: storage);
  final restored = await engine.restore(
    GameState.empty.copyWith(memberId: 100),
    now,
    allowLegacy: false,
  );
  expect(engine.persistenceError, isNull, reason: row['name'] as String);
  expect(restored.quests, contains(id), reason: row['name'] as String);
  final steps = engine.stepsFor(id);
  expect(
    steps.map((step) => step.count).toList(),
    (row['counts'] as Map).values.toList(),
    reason: row['name'] as String,
  );
  return restored.quests[id]!;
}

void _expectCompositeDisplay(
  GameQuest quest,
  Map<String, dynamic> row,
  BuildContext context,
) {
  final reason = row['name'] as String;
  expect(quest.state, 2, reason: reason);
  expect(quest.progressFlag, row['flag'], reason: reason);
  expect(quest.progressCurrent, row['count'], reason: reason);
  expect(quest.progressRequired, row['required'], reason: reason);
  expect(
    quest.displayProgressLabel,
    (row['label'] as String).replaceAll(' / ', '/'),
    reason: reason,
  );
  expect(
    quest.progressColor(context),
    _intentColors(context)[row['intent']],
    reason: reason,
  );
}

class _Composite {
  const _Composite(
    this.name,
    this.questId,
    this.flag,
    this.counts,
    this.count,
    this.required,
    this.intent,
  );
  final String name;
  final int questId;
  final int flag;
  final List<int> counts;
  final int count;
  final int required;
  final String intent;

  Map<String, dynamic> toOracleRow() {
    final requirements = _verifiedCompositeRequirements[questId]!;
    final keys = requirements.keys.toList();
    return {
      'name': name,
      'questId': questId,
      'flag': flag,
      'state': 2,
      'counts': {
        for (var index = 0; index < keys.length; index++)
          keys[index]: counts[index],
      },
      'requirements': requirements,
      'count': count,
      'required': required,
      'intent': intent,
      'label': '$count / $required',
    };
  }
}

class _CompositeStorage implements QuestProgressStorage {
  _CompositeStorage(this.value);
  String value;
  @override
  Future<String?> read(int account) async => value;
  @override
  Future<void> write(int account, String value) async {
    this.value = value;
  }
}

GameQuest _quest({
  int? current,
  int? total,
  int flag = 0,
  int state = 2,
  bool? verified,
}) => GameQuest(
  id: 912,
  title: 'test',
  detail: '',
  category: 2,
  type: 4,
  state: state,
  progressFlag: flag,
  progressCurrent: current,
  progressRequired: total,
  localCompletionVerified: verified,
);

Future<BuildContext> _context(WidgetTester tester, AppThemeMode mode) async {
  late BuildContext context;
  await tester.pumpWidget(
    MaterialApp(
      theme: ThemeData(extensions: [AppPalette.forMode(mode)]),
      home: Builder(
        builder: (value) {
          context = value;
          return const SizedBox();
        },
      ),
    ),
  );
  return context;
}

Map<String, Color> _intentColors(BuildContext context) {
  final palette = AppPalette.of(context);
  final neutral = palette.muted;
  final warning = palette.isDark ? const Color(0xffd4a85f) : palette.gold;
  final primary = palette.isDark ? const Color(0xff8ec6e8) : palette.info;
  final success = palette.isDark ? const Color(0xff67d6a3) : palette.success;
  return {
    'n': neutral,
    'none': neutral,
    'w': warning,
    'warning': warning,
    'p': primary,
    'primary': primary,
    's': success,
    'success': success,
  };
}

String _intentName(String symbol) => switch (symbol) {
  'n' => 'none',
  'w' => 'warning',
  'p' => 'primary',
  's' => 'success',
  _ => throw ArgumentError.value(symbol),
};
